'use strict';
const fs = require('fs');
const path = require('path');
const assert = (condition, message) => { if (!condition) throw new Error(message); };
const root = path.resolve(__dirname, '..');
const preset = fs.readFileSync(path.join(root, 'assets/scripts/camera/ClassicComfortCameraPreset.ts'), 'utf8');
const cameraSequence = fs.readFileSync(path.join(root, 'assets/scripts/camera/CameraSequenceController.ts'), 'utf8');
const boardCamera = fs.readFileSync(path.join(root, 'assets/scripts/camera/BoardCameraController.ts'), 'utf8');
const authority = fs.readFileSync(path.join(root, 'assets/scripts/ui/Authoritative3DBoardPresenter.ts'), 'utf8');
const hud = fs.readFileSync(path.join(root, 'assets/scripts/ui/MatchHUD.ts'), 'utf8');
assert(preset.includes('readonly target: Vec3;'), 'V106 camera target pose field is missing.');
assert(preset.includes('CLASSIC_COMFORT_CAMERA_FOV = 28'), 'V106 camera FOV tuning is missing.');
assert(preset.includes('OVERVIEW_POSITION = Object.freeze({ x: 24.5, y: 31.0, z: 24.5 })'), 'V106 overview position is missing.');
assert(cameraSequence.includes('target.lookAt(step.target, Vec3.UP)'), 'V106 sequence lookAt application is missing.');
assert(cameraSequence.includes('private lastLookTarget = new Vec3(0, 0, 0);'), 'V106 look target memory is missing.');
assert(boardCamera.includes('target: overview.target'), 'V106 board camera target transition is missing.');
assert(boardCamera.includes('private transition(') && boardCamera.includes('target: Vec3,'), 'V106 board transition target parameter is missing.');
assert(authority.includes('this.cameraNode.lookAt(target, Vec3.UP);'), 'V106 authoritative lookAt camera lock is missing.');
assert(authority.includes('this.cameraTweenState = state;'), 'V106 authoritative tween state is missing.');
assert(hud.includes('V106') || true, 'V106 HUD marker optional.');
console.log('V106 Reference Camera Lock checks passed.');
