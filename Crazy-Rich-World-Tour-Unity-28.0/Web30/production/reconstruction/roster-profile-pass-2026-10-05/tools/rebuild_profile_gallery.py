#!/usr/bin/env python3
"""Rebuild into a fresh external directory; frozen prefix and receipt stay untouched."""
import argparse, hashlib, json, pathlib, subprocess, sys
sys.dont_write_bytecode=True
from verify_profile_source import GALLERY_SHA, require, sha
from restore_offline_gallery import inspect_archive

def rebuild(roster,build_dir,receipt=None):
    roster=roster.resolve(strict=True);build_dir=build_dir.resolve()
    require(not build_dir.exists() and not build_dir.is_relative_to(roster) and not roster.is_relative_to(build_dir),'Gallery output must be fresh outside frozen source')
    frozen_path=roster/'BUKA-REVIEW-MODEL.viewer-receipt.json';frozen_raw=frozen_path.read_bytes();frozen=json.loads(frozen_raw)
    manifest_path=roster/'review-manifest.json';manifest_raw=manifest_path.read_bytes()
    require(frozen.get('viewer_sha256')==GALLERY_SHA and frozen.get('manifest_sha256')==sha(manifest_raw) and frozen.get('visual_approval') is False and frozen.get('game_integration') is False,'Frozen gallery receipt mismatch')
    zip_report=inspect_archive(roster/'OFFLINE-GALLERY.zip')
    require(zip_report['html_sha256']==frozen['viewer_sha256'] and zip_report['html_bytes']==frozen['viewer_bytes'],'Frozen gallery ZIP/receipt mismatch')
    if receipt:
        receipt=receipt.resolve();require(not receipt.exists() and not receipt.is_relative_to(roster) and not receipt.is_relative_to(build_dir),'Gallery report must be new outside frozen sources/build directory')
    build_dir.mkdir(parents=True,exist_ok=False);html=build_dir/'BUKA-REVIEW-MODEL.html'
    subprocess.run([sys.executable,'-B',str(roster/'viewer/build_offline_gallery.py'),'--manifest',str(manifest_path),'--output',str(html),'--expected-output-sha256',GALLERY_SHA],check=True)
    generated=json.loads(html.with_suffix('.viewer-receipt.json').read_bytes());raw=html.read_bytes()
    require(generated==frozen and sha(raw)==GALLERY_SHA and len(raw)==frozen['viewer_bytes'],'Gallery generated bytes/receipt metadata differ')
    require(frozen_path.read_bytes()==frozen_raw and manifest_path.read_bytes()==manifest_raw,'Frozen receipt/manifest changed')
    existing=roster/'BUKA-REVIEW-MODEL.html'
    if existing.exists():require(existing.read_bytes()==raw,'Tracked source HTML differs from generated gallery')
    report={'schema':'crwt.alexia_profile_gallery_rebuild.v1','passed':True,'gallery_sha256':GALLERY_SHA,'bytes':len(raw),
            'frozen_receipt_JSON_metadata_equal':True,'frozen_receipt_bytes_preserved':True,'frozen_prefix_overwrites':False,
            'source_html_storage':'zip','source_gallery_archive_sha256':zip_report['archive_sha256'],
            'output_html':str(html),'no_network_or_generation':True,'approved':False,'gameIntegrated':False}
    if receipt:
        receipt.parent.mkdir(parents=True,exist_ok=True)
        with receipt.open('x',encoding='utf-8',newline='\n') as f:f.write(json.dumps(report,indent=2)+'\n')
    return report

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--roster',type=pathlib.Path,required=True);p.add_argument('--build-dir',type=pathlib.Path,required=True);p.add_argument('--receipt',type=pathlib.Path)
    a=p.parse_args();print(json.dumps(rebuild(a.roster,a.build_dir,a.receipt),indent=2))
if __name__=='__main__':main()
