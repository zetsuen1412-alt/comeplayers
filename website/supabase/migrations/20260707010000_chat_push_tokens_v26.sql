begin;

create table if not exists public.chat_push_tokens (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  expo_push_token text not null,
  platform text not null default 'android',
  enabled boolean not null default true,
  last_seen_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint chat_push_tokens_platform_check check (platform in ('android', 'ios')),
  constraint chat_push_tokens_token_unique unique (expo_push_token)
);

create index if not exists chat_push_tokens_user_enabled_idx
  on public.chat_push_tokens (user_id, enabled)
  where enabled = true;

alter table public.chat_push_tokens enable row level security;

revoke all on table public.chat_push_tokens from anon, authenticated;
grant all on table public.chat_push_tokens to service_role;
grant usage, select on sequence public.chat_push_tokens_id_seq to service_role;

comment on table public.chat_push_tokens is
  'Server-managed Expo push tokens for ComePlayers message notifications.';

commit;
