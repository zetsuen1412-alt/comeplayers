/** Unknown values remain unchanged so provider codes and identifiers stay inspectable. */
export function adminLabel(value: unknown): string {
  if (value === null || value === undefined) return "—";
  const text = String(value);
  const key = text.trim().toLowerCase();
  return Object.hasOwn(labels, key) ? labels[key] : text;
}

/** Translate known system messages at the display boundary, never arbitrary customer text. */
export function adminText(value: unknown): string {
  if (value === null || value === undefined || value === false) return "";
  const text = typeof value === "string" ? value : value instanceof Error ? value.message : String(value);
  const key = text.trim();
  if (Object.hasOwn(adminMessages, key)) return adminMessages[key];
  const request = /^Request failed with status (\d{3})\.$/.exec(key);
  if (request) return `Permintaan gagal dengan status ${request[1]}.`;
  return text;
}

/** The scope identifier remains unchanged in requests and audit records. */
export function adminScanScope(value: string): string {
  const scope = /^financial:(\d+)d$/.exec(value);
  return scope ? `Keuangan · ${scope[1]} hari` : value;
}

